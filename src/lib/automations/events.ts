export function findEventDefinition(key: string): AutomationEventDefinition | undefined {
  return AUTOMATION_EVENT_DEFINITIONS.find((e) => e.key === key);
}

export function listEventDefinitions(): AutomationEventDefinition[] {
  return AUTOMATION_EVENT_DEFINITIONS;
}

/** Strips a raw payload down to exactly the fields the event definition declares (plus previous/current/changedFields for transition events) — the one place "no incluyas contenido completo" is actually enforced, never trusted to each call site. */
export function sanitizeEventPayload(eventKey: string, raw: Record<string, unknown>): Record<string, unknown> {
  const def = findEventDefinition(eventKey);
  if (!def) return {};
  const clean: Record<string, unknown> = {};
  for (const field of def.fields) {
    if (field.key in raw) clean[field.key] = raw[field.key];
  }
  if (def.hasTransition) {
    if ("previous" in raw) clean.previous = raw.previous;
    if ("current" in raw) clean.current = raw.current;
    if ("changedFields" in raw) clean.changedFields = raw.changedFields;
  }
  return clean;
}
