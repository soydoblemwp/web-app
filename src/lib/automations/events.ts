/**
 * The central, typed registry of internal events (spec section 8) — the
 * SINGLE place every event key, its allowed payload fields, and its
 * resource type live. Nothing else in this codebase publishes an event
 * under a free-floating string; every publisher and every condition/mapping
 * editor resolves an event definition through `findEventDefinition` below.
 */

export type AutomationEventFieldType = "string" | "number" | "boolean" | "date" | "string[]";

export interface AutomationEventFieldSpec {
  key: string;
  label: string;
  type: AutomationEventFieldType;
}

export interface AutomationEventDefinition {
  /** Stable key — never renamed once shipped; publishing code and stored WorkflowAutomationEvent.type rows both reference this. */
  key: string;
  label: string;
  description: string;
  resourceType: string;
  schemaVersion: number;
  /** Fields the payload is allowed to carry — never the resource's full row (spec sections 8/16: "no incluyas secretos ni contenido completo innecesario"). */
  fields: AutomationEventFieldSpec[];
  /** True for "X changed" events — payload additionally carries `previous`/`current`/`changedFields` (spec section 16). */
  hasTransition: boolean;
}

