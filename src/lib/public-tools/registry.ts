export function getAllPublicTools(): PublicToolDefinition[] {
  return PUBLIC_TOOL_DEFINITIONS;
}

export function findPublicTool(slug: string): PublicToolDefinition | undefined {
  return PUBLIC_TOOL_DEFINITIONS.find((tool) => tool.slug === slug);
}

export function getPublicToolCategory(slug: string): PublicToolCategoryDefinition | undefined {
  return PUBLIC_TOOL_CATEGORIES.find((category) => category.slug === slug);
}

export function getPublicToolsByCategory(category: string): PublicToolDefinition[] {
  return PUBLIC_TOOL_DEFINITIONS.filter((tool) => tool.category === category);
}

export function getFeaturedPublicTools(): PublicToolDefinition[] {
  return PUBLIC_TOOL_DEFINITIONS.filter((tool) => tool.featured);
}

export function getNewPublicTools(): PublicToolDefinition[] {
  return PUBLIC_TOOL_DEFINITIONS.filter((tool) => tool.isNew);
}

export function getRelatedPublicTools(slug: string): PublicToolDefinition[] {
  const tool = findPublicTool(slug);
  if (!tool) return [];
  return tool.relatedTools.map((relatedSlug) => findPublicTool(relatedSlug)).filter((t): t is PublicToolDefinition => Boolean(t));
}

/** Categories that actually have at least one available tool — the center must never render an empty category. */
export function getNonEmptyPublicToolCategories(): PublicToolCategoryDefinition[] {
  return PUBLIC_TOOL_CATEGORIES.filter((category) => PUBLIC_TOOL_DEFINITIONS.some((tool) => tool.category === category.slug));
}
